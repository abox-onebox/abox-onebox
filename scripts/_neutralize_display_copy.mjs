let applied = 0;
let skipped = 0;
let failed = 0;
const failures = [];

for (const [rel, items] of Object.entries(REPLACEMENTS)) {
  const abs = resolve(ROOT, rel);
  if (!existsSync(abs)) {
    failures.push(`文件不存在：${rel}`);
    failed++;
    continue;
  }
  const lines = readFileSync(abs, 'utf8').split('\n');
  let fileChanged = 0;
  for (const [ln, from, to] of items) {
    const idx = ln - 1;
    if (idx < 0 || idx >= lines.length) {
      failures.push(`${rel}:${ln} 行号越界（文件共 ${lines.length} 行）`);
      failed++;
      continue;
    }
    if (lines[idx].includes(from)) {
      lines[idx] = lines[idx].replace(from, to);
      fileChanged++;
    } else if (lines[idx].includes(to)) {
      skipped++; // 已应用（幂等）
    } else {
      failures.push(`${rel}:${ln} 未命中旧串：「${from.slice(0, 40)}」`);
      failed++;
    }
  }
  if (fileChanged) {
    writeFileSync(abs, lines.join('\n'), 'utf8');
    applied += fileChanged;
    console.log(`✔ ${rel} · ${fileChanged} 处`);
  }
}

console.log(`\n=== 去餐饮化替换：本次 ${applied} 处生效，已存在 ${skipped} 处跳过，${failed} 处失败 ===`);
if (failures.length) {
  for (const f of failures) console.log('  ✘ ' + f);
  process.exit(1);
}
process.exit(0);
