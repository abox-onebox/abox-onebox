/**
 * 财务域角色白名单（**单一真相**）
 *
 * ## 为什么要单独一个文件
 *
 * 财务域的两级白名单在 M35 各批次里**各自硬编码**过：D35 佣金入账、D39 余额调整、
 * D41/D42 退款审批，三处都写着字面量 `'super_admin', 'admin', 'finance'`。
 * 四个字面量副本的后果不是「编译不过」，而是**静默漂移**：
 * 改了一处、忘了另一处，就会出现「按钮亮着、点了 `10003`」（出参说可点、`@Roles` 说不行）
 * 或更糟的「按钮灰着、其实有权限」（本该受管控的资金动作被默默放行）。
 * 二者都不会报错，只会在某次审计里才被发现。
 *
 * ⚠️ 判别标准：**「谁能动钱」是一个业务概念，不是某个端点的实现细节**。
 *    所以它属于域级常量，不属于任何单个 service。
 *
 * ## 两个集合的边界
 *
 * | 集合 | 含义 | 端点举例 |
 * |------|------|----------|
 * | `FINANCE_READ_ROLES` | 能**看**财务数据（含运营，用于跟进「为什么佣金没结」「今天哪几笔对不上」） | D33 / D34 / D38 / D40 / D43 / D44 / D45 |
 * | `FUND_ACTION_ROLES` | 能**动钱**（入账 / 调账 / 退不退 / 批不批提现） | D35 / D39 / D41 / D42 / D46 |
 *
 * `operator` **只在读侧**：它的职责是「看见异常并上报」，不是「拍板把钱发出去」。
 * `viewer` 两侧都不在 —— 它的菜单只有 4 个看板页，没有财务入口
 * （与 D47–D50 看板刻意**含** `viewer` 的理由正好相反：那边 viewer 的菜单**只有**看板页，
 * 漏了就整个角色不可用）。
 *
 * ⚠️ 与菜单**同源**：`apps/admin-web/src/constants/index.ts` 的 `ADMIN_NAV`
 *    里 `/finance/*` 出现在 `admin` / `operator` / `finance` 的菜单中，
 *    故此处不含 `viewer`。授权了就必须有入口，有入口就必须有权限 —— 两边都不许单边漂移。
 */

/** 可**查看**财务域数据的角色（类级白名单，含 `operator`） */
export const FINANCE_READ_ROLES = ['super_admin', 'admin', 'finance', 'operator'] as const;

/**
 * 可执行**资金动作**的角色（方法级白名单，**不含 `operator`**）
 *
 * 「决定钱退不退 / 发不发 / 记不记账」不是运营专员的职权，与
 * `refund-admin.controller.ts` D41/D42、`finance-admin.controller.ts` D35/D39、
 * 以及本域 **D46 提现审批**共用同一份定义。
 */
export const FUND_ACTION_ROLES = ['super_admin', 'admin', 'finance'] as const;
