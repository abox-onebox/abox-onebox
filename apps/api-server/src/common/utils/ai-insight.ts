/**
 * AI 留档的「这算不算一次真产出」判据（纯函数 · 有单测）
 *
 * ## 为什么需要它
 *
 * 15 个 AI 节点的方法体在**成功**与**失败**时都返回 `string` —— 失败不是抛异常，
 * 而是返回一句人话提示（「取不到日期，我先不动。稍后再试。」）。这是对交互友好的
 * 设计，但让「留档」失去了类型层的区分依据：调用方拿到 `string`，**看不出这一趟
 * 到底是 AI 给出了结论，还是只是报了个错**。
 *
 * 若不加判据地全量留档，台账会被大量失败提示灌满——
 * 那正是 2026-11-04 在开团草稿上踩过的坑的翻版：`dropped=0` 且 `rows=0` 时，
 * 页面只显示「AI 未给」，看起来像 AI 没干活，实际是展示层把结论丢了。
 * **台账一旦被噪声灌满，就等于没有台账**（没人会翻）。
 *
 * ## 判据为什么是「长度 / 行数」而不是关键词黑名单
 *
 * 试过的两条路都被否掉了：
 * - **关键词黑名单**（匹配「取不到」「没法」「先不动」…）：失败文案是**人写的，
 *   会随文案优化而变**，每改一句就得回来加词；漏一个就把失败当成功留档。
 *   且新节点接入时没人会记得来登记。
 * - **让调用方显式传 `ok: boolean`**：那要改 15 个方法体的签名（每个都要新增
 *   返回值位），改动面大、回归风险高，为的只是拿一个本来可从形态推断的信号。
 *
 * 实测这类项目的文案形态是**稳定分离的**：
 * - 失败提示：1~2 行、几十字、一句人话（「取不到楼群清单，没法出开团草稿」）
 * - 真产出：多段 markdown 报告，**标题 + 列表 + 结论**，通常 800~3000 字
 *
 * 两者在「长度」和「行数」上相差一个量级，故用阈值判断，且**取「或」**：
 * 一行超长文本（模型偶尔不给换行）与多行短文本（极简结论）都能覆盖。
 *
 * ## ⚠️ 已知边界（如实标注）
 * - 若某节点真的产出「仅一句话」的结论（如「今天没有异常」），会被判为失败而**不留档**。
 *   取舍：宁可漏掉极少数一句话结论，也不让失败提示污染台账（后者代价高得多）。
 * - 阈值是经验值，不是原理值。节点文案大幅变短时需重新评估——
 *   故单测里钉了「典型失败文案必须判 false」与「典型报告必须判 true」两侧样本。
 */

/** 视为「真产出」的最小字数（失败提示实测最长约 60 字） */
const MIN_CHARS = 200;

/** 视为「真产出」的最小非空行数（报告通常是标题 + 若干条目） */
const MIN_LINES = 6;

/**
 * 这段文本是不是 AI 的真产出（而非失败/跳过提示）。
 *
 * @param text 节点方法返回的文本
 */
export function looksLikeRealOutput(text: string): boolean {
  const t = (text ?? '').trim();
  if (!t) return false;
  if (t.length >= MIN_CHARS) return true;
  const nonEmptyLines = t.split('\n').filter((l) => l.trim().length > 0).length;
  return nonEmptyLines >= MIN_LINES;
}

/**
 * 从报告正文里取一句标题（列表页展示用）。
 *
 * 优先取第一个 markdown 标题（`# xxx` / `## xxx`）——各节点的报告都以此开头；
 * 取不到则退回首个非空行；再退回节点名。**不做长句截断**（截断在这里会切掉定语，
 * 反而看不懂），由调用方按列宽处理。
 */
export function pickInsightTitle(text: string, fallback: string): string {
  const lines = (text ?? '')
    .split('\n')
    .map((l) => l.replace(/^#{1,6}\s*/, '').trim())
    // 过滤掉「（AI 生成）」这类括注行：它不构成标题，但常在首行，跳过继续找
    .filter((l) => l.length > 0 && !/^[（(]/.test(l));
  const first = lines[0] ?? '';
  return first ? first.slice(0, 120) : fallback;
}
