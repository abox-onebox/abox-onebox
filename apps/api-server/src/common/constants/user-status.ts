/**
 * `ab_user.status` 取值（tinyint）
 *
 * ⚠️ **实体注释就是本枚举的原文**（`user.entity.ts:60` 原写「1正常 2黑名单」），
 *    本文件只是把它变成**可引用的符号** —— 项目里 `leader.status === LeaderStatus.ACTIVE`
 *    已成惯例（`leader-status.ts` 头注：「禁止再写字面量」），用户状态此前一直是裸字面量。
 *
 * ⚠️ **3 = 已注销**（M5-20 新增）**不是**「更严重的黑名单」：
 *    · `2 黑名单` = **平台处罚**（运营在后台拉黑），用户只能申诉；
 *    · `3 已注销` = **用户自主发起**，恢复走客服人工，且个人信息已匿名化。
 *    两者都让账号不可用，但**登录时的错误码不同**（20006 / 20014），
 *    因为用户要执行的动作不同（申诉 / 找客服恢复）—— 合一个码会让注销过的人
 *    以为被封号了。这与 40015/40002 的取舍同源：形态相似、排查入口不同。
 */
export enum UserStatus {
  /** 正常可用 */
  NORMAL = 1,
  /** 黑名单（运营拉黑，登录拦 20006） */
  BLACKLIST = 2,
  /** 已注销（用户自助注销，登录拦 20014） */
  CANCELED = 3,
}

/** 状态文案（后台用户页 / 操作日志共用；与实体注释逐字一致） */
export const USER_STATUS_LABEL: Record<UserStatus, string> = {
  [UserStatus.NORMAL]: '正常',
  [UserStatus.BLACKLIST]: '黑名单',
  [UserStatus.CANCELED]: '已注销',
};

/**
 * 注销后写入的昵称（**匿名化**，不保留原昵称）
 *
 * ⚠️ 原因：昵称属个人信息，且它出现在**历史订单**与后台列表里（订单表存的是
 *    快照还是引用见订单域口径）。注销的合规含义是「删除或匿名化」，
 *    直接置空会让端上显示 `null`；给一个中性的占位串**既匿名又不变形**。
 *    ⭐ 与 `deleted_at` 一起构成「这条记录已注销」的**双证据**。
 */
export const CANCELED_NICKNAME = '已注销用户';
