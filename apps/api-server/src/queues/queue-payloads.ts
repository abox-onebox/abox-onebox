/**
 * 队列任务载荷（M4-3）
 *
 * ## 为什么单独一个文件
 *
 * 载荷的**形状**是生产端（业务服务）与消费端（`*.consumer.ts`）之间的契约。
 * 若把它定义在消费者文件里，业务服务就要 import 消费者（方向倒置，
 * 且会形成「服务 ↔ 消费者」的循环 import）。放这里：两边都只依赖这一个纯类型文件。
 *
 * ## 写法纪律
 *
 * · **只放「重建执行所需的最小事实」**，不放实体对象 —— 队列里的数据会跨进程
 *   存活（Redis），塞进一个快照意味着重试时用的是**过期状态**；
 *   消费者应带着主键回库读最新状态再执行。
 * · 金额一律**分**（与 Provider 层一致），不在这里做单位换算。
 */

/**
 * `order-paid` —— 支付入账重试
 *
 * 何时入队：微信支付回调（或 mock 自动回调）**入账失败**时。
 * 为什么需要：回调必须快速回 `SUCCESS`（否则微信重推形成风暴），
 * 故入账失败不能靠「让微信再推一次」；此前只能等次日对账兜底，
 * 而 `markPaid` 本身**已幂等**（状态检查 + `uk_payment_order`），
 * 完全可以安全地立即重试。
 */
export interface OrderPaidPayload {
  orderNo: string;
  transactionId: string;
  amountFen: number;
  raw?: unknown;
}

/**
 * `refund-apply` —— 微信退款执行（含重试）
 *
 * 何时入队：
 *   · 退款审批 / 强制退款时**微信通道调用失败**（首次同步尝试之后）；
 *   · 支付回调延迟到达且订单已取消 → 自动退款（罕见异常路径，直接入队）。
 *
 * ⭐ `refundNo` 必带：它是微信侧的**幂等键**（`out_refund_no`）——
 * 重试携带同一个 `refundNo`，微信会把重复请求识别为同一笔退款，
 * 因此「重试」永远不会变成「重复出款」。这是允许自动重试的前提。
 */
export interface RefundApplyPayload {
  refundId: number;
  orderNo: string;
  refundNo: string;
  /** 走微信通道的金额（分）= 订单实付（余额抵扣部分不走通道） */
  wxFen: number;
  /** 原订单总额（分）—— 微信退款接口要求带 */
  totalFen: number;
  reason: string;
}

/**
 * `settle-orders` —— 结算后续（佣金入账通知）
 *
 * 何时入队：`commission-settle` 跑批（T+1 02:00）把 `pending` 佣金入账之后，
 * **按团长逐个入队**（一个团长一条任务）。
 * 为什么异步：通知是**外部 IO**（微信订阅消息），跑批不该因为通知慢而拖长；
 * 且通知失败必须能重试，而跑批本身不会为「通知失败」重跑。
 *
 * ## ⭐ 为什么是「按团长」而不是「整批一条」
 *
 * 订阅消息**必须指定收件人**（`openid`）。一条整批汇总的任务没有收件人 ——
 * 消费者只能写一条系统日志，「通知用户」这件事实际没发生，而且**看起来像成功了**。
 * 拆成一人一条后：
 *   · 每个团长的通知**独立重试**（某个人投递失败不会连累其他人）；
 *   · 死信粒度 = 一个人，运维能看到「谁的入账通知没发出去」；
 *   · 顺带绕开了「多实例下一个大任务卡住整批」的问题。
 * 代价是任务条数 = 当日入账团长数（实际量级：个位数到几十条），完全可接受。
 *
 * ⚠️ 载荷里**只有金额与条数**，没有佣金明细 —— 通知只讲「入账了多少钱」，
 *    明细在小程序里看（通知里塞明细既超长又过时）。
 */
export interface SettleOrdersPayload {
  /** 结算针对的出餐日（`ab_commission.meal_date`） */
  mealDate: string;
  /**
   * 收件团长（`ab_team_leader.id`）
   *
   * ⚠️ 用 `id` 而非 `userId`：团长的**业务主键**在队列里跨进程存活期间更稳定
   *    （`userId` 是账号维度，这里只是「怎么找到这个人的余额」），
   *    `leader → user → openid` 的换算发生在投递侧（`MessageService`），
   *    与 `refund_result` 走同一条换算链。
   */
  leaderId: number;
  /** 该团长本次入账的佣金**笔数** */
  settledCount: number;
  /** 该团长本次入账金额（分） */
  amountFen: number;
}
