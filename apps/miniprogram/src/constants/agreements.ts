export type AgreementType = 'user' | 'privacy';

export interface AgreementSection {
  /** 小节标题 */
  heading: string;
  /** 段落（每项一段） */
  paragraphs?: string[];
  /** 条目列表 */
  items?: string[];
  /** `items` 是否需要序号（true = 有序，false / 缺省 = 圆点） */
  ordered?: boolean;
}

export interface AgreementDoc {
  type: AgreementType;
  title: string;
  /** 文档版本（`-draft` 后缀 = 未定稿） */
  version: string;
  /** 版本日期 */
  updatedAt: string;
  /** 文首引言（每项一段） */
  preamble: string[];
  sections: AgreementSection[];
}

